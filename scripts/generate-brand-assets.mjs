async function assertBytes(path, expected) {
  let actual;
  try { actual = await readFile(join(root, path)); } catch { throw new Error(`Missing generated asset: ${path}`); }
  if (!actual.equals(expected)) throw new Error(`Generated asset drift: ${path}`);
}

async function listFiles(directory, prefix) {
  let entries;
  try { entries = await readdir(join(root, directory), { withFileTypes: true }); } catch { return []; }
  const files = [];
  for (const entry of entries) {
    const child = `${directory}/${entry.name}`;
    if (entry.isDirectory()) files.push(...await listFiles(child, prefix));
    else if (entry.isFile()) files.push(relative(root, join(root, child)));
    else throw new Error(`Generated output tree contains a non-file entry: ${child}`);
  }
  return files.filter((path) => path.startsWith(prefix));
}

