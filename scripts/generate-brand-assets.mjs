function sourceFilename(sourcePath) {
  return sourcePath.slice(sourcePath.lastIndexOf("/") + 1);
}

function finderPath({ x, y }) {
  return `<path fill-rule="evenodd" d="M${x} ${y}h12v12H${x}zM${x + 3} ${y + 3}v6h6v-6z"/>`;
}

function markBody() {
  return [
    ...brandGeometry.finderPatterns.map(finderPath),
    ...brandGeometry.rectangles.map(({ x, y, width, height }) =>
      `<rect x="${x}" y="${y}" width="${width}" height="${height}"/>`),
  ].join("");
}

function staticMark(color, identityId = "mark-only") {
  return `${generatedMarker}\n<svg xmlns="http://www.w3.org/2000/svg" data-brand-identity="${identityId}" viewBox="${brandGeometry.viewBox}" fill="${color}">${markBody()}</svg>\n`;
}

function staticLockup(color, identityId, definitions, uses) {
  return `${generatedMarker}\n<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" data-brand-identity="${identityId}" viewBox="0 0 160 32" fill="${color}">${definitions}<g>${markBody()}</g><g transform="translate(40 6.5)">${uses}</g></svg>\n`;
}

function crc32(bytes) {
  let crc = 0xffffffff;
  for (const byte of bytes) {
    crc ^= byte;
    for (let bit = 0; bit < 8; bit += 1) crc = (crc >>> 1) ^ (crc & 1 ? 0xedb88320 : 0);
  }
  return (crc ^ 0xffffffff) >>> 0;
}

function pngChunk(type, data) {
  const typeBytes = Buffer.from(type);
  const length = Buffer.alloc(4);
  length.writeUInt32BE(data.length);
  const checksum = Buffer.alloc(4);
  checksum.writeUInt32BE(crc32(Buffer.concat([typeBytes, data])));
  return Buffer.concat([length, typeBytes, data, checksum]);
}

function insideRoundedSquare(x, y, size) {
  const radius = size * 0.18;
  const insetX = Math.max(radius - x, 0, x - (size - radius - 1));
  const insetY = Math.max(radius - y, 0, y - (size - radius - 1));
  return insetX * insetX + insetY * insetY <= radius * radius;
}

function insideFinder(sourceX, sourceY, finder) {
  const withinOuter = sourceX >= finder.x && sourceX < finder.x + 12 &&
    sourceY >= finder.y && sourceY < finder.y + 12;
  const withinHole = sourceX >= finder.x + 3 && sourceX < finder.x + 9 &&
    sourceY >= finder.y + 3 && sourceY < finder.y + 9;
  return withinOuter && !withinHole;
}

function insideMark(x, y, size) {
  const sourceX = ((x + 0.5) / size) * 32;
  const sourceY = ((y + 0.5) / size) * 32;
  return brandGeometry.finderPatterns.some((finder) => insideFinder(sourceX, sourceY, finder)) ||
    brandGeometry.rectangles.some((rectangle) => sourceX >= rectangle.x &&
      sourceX < rectangle.x + rectangle.width && sourceY >= rectangle.y &&
      sourceY < rectangle.y + rectangle.height);
}

function faviconPng(size, background, foreground) {
  const scanlines = Buffer.alloc((size * 4 + 1) * size);
  for (let y = 0; y < size; y += 1) {
    const row = y * (size * 4 + 1);
    for (let x = 0; x < size; x += 1) {
      const offset = row + 1 + x * 4;
      const pixel = insideMark(x, y, size) ? foreground : background;
      scanlines.set([pixel[0], pixel[1], pixel[2], insideRoundedSquare(x, y, size) ? 255 : 0], offset);
    }
  }
  const header = Buffer.alloc(13);
  header.writeUInt32BE(size, 0);
  header.writeUInt32BE(size, 4);
  header[8] = 8;
  header[9] = 6;
  return Buffer.concat([
    Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]),
    pngChunk("IHDR", header),
    pngChunk("IDAT", deflateSync(scanlines, { level: 9 })),
    pngChunk("IEND", Buffer.alloc(0)),
  ]);
}

function faviconIco(frames) {
  const header = Buffer.alloc(6 + frames.length * 16);
  header.writeUInt16LE(1, 2);
  header.writeUInt16LE(frames.length, 4);
  let offset = header.length;
  frames.forEach(({ size, bytes }, index) => {
    const entry = 6 + index * 16;
    header[entry] = size;
    header[entry + 1] = size;
    header.writeUInt16LE(1, entry + 4);
    header.writeUInt16LE(32, entry + 6);
    header.writeUInt32LE(bytes.length, entry + 8);
    header.writeUInt32LE(offset, entry + 12);
    offset += bytes.length;
  });
  return Buffer.concat([header, ...frames.map(({ bytes }) => bytes)]);
}

async function readAndValidateSources() {
  const sourceDirectory = join(root, "docs/template/app/public");
  const actualSourceFiles = (await readdir(sourceDirectory)).filter((file) => file.endsWith(".svg")).sort();
  const declaredSourceFiles = templateAssetSources.map(({ sourcePath }) => sourceFilename(sourcePath)).sort();
  if (JSON.stringify(actualSourceFiles) !== JSON.stringify(declaredSourceFiles)) {
    throw new Error("Immutable template SVG inventory differs from the closed 17-source register.");
  }
  const records = [];
  for (const source of templateAssetSources) {
    const bytes = await readFile(join(root, source.sourcePath));
    if (bytes.length !== source.bytes || sha256(bytes) !== source.sha256) {
      throw new Error(`Immutable template source drift: ${source.sourcePath}`);
    }
    const parsed = validateSafeSvg(bytes.toString("utf8"), {
      expectedViewBox: `0 0 ${source.intrinsic.width} ${source.intrinsic.height}`,
      allowSourceText: sourceFilename(source.sourcePath) === "logo.svg",
    });
    if (parsed.width !== source.intrinsic.width || parsed.height !== source.intrinsic.height) {
      throw new Error(`Template source intrinsic dimension drift: ${source.sourcePath}`);
    }
    records.push({ source, bytes });
  }
  return records;
}

function themeAuditColors(tokens, themeId) {
  const theme = tokens.color?.primitive?.audit?.template?.[themeId];
  if (!theme) throw new Error(`Missing canonical token theme: ${themeId}`);
  return [theme.bg, theme.surface, theme.border, theme.accent].map((token) => token?.$value?.hex?.toUpperCase());
}

function tokenHex(theme, path) {
  const hex = theme[path]?.$value?.hex;
  if (!/^#[0-9a-f]{6}$/i.test(hex ?? "")) throw new Error(`Canonical theme token is not a six-digit sRGB color: ${path}.`);
  return hex.toUpperCase();
}

function rgbaBytes(hex) {
  return [1, 3, 5].map((offset) => Number.parseInt(hex.slice(offset, offset + 2), 16)).concat(255);
}

function validateThemeSwatch(source, svg, tokens) {
  const filename = sourceFilename(source.sourcePath);
  const themeId = filename.match(/^theme-swatch-(.+)\.svg$/)?.[1];
  if (!themeId || !requiredThemeIds.includes(themeId)) throw new Error(`Invalid theme swatch ID: ${filename}`);
  const authoredColors = new Set([...svg.matchAll(/(?:fill|stroke)="(#[0-9A-Fa-f]{6})"/g)].map((match) => match[1].toUpperCase()));
  for (const expected of themeAuditColors(tokens, themeId)) {
    if (!expected || !authoredColors.has(expected)) throw new Error(`Theme swatch ${themeId} does not project canonical token color ${expected}.`);
  }
  return themeId;
}

function derivativeMetadata({ id, role, derivation, outputPath, mime, intrinsic, colorMode,
  accessibilityMode, bytes, sourceParityIds, provenanceReference, ...extra }) {
  return { id, role, derivation, outputPath, mime, intrinsic, colorMode, accessibilityMode,
    generated: true, bytes: bytes.length, sha256: sha256(bytes), sourceParityIds, provenanceReference, ...extra };
}

